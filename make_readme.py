"""Write README.md, computing every number in it from the raw source files.

Nothing is typed in by hand or read off a figure: the figures' headline values
are recomputed here from the original Fed zips in data/raw/ (via the same
loaders process_data.py uses), the 2025 margins of error come from the Fed's
replicate weights, and the result is cross-checked against the processed
tables that plot.py draws from. Rerun after any change to the data or method:

    .venv/bin/python make_readme.py
"""

from pathlib import Path

import numpy as np
import pandas as pd

import process_data as pdata
import standard_errors as se

ROOT = Path(__file__).resolve().parent
PROCESSED = ROOT / "data" / "processed"


def medians_by_group(df, group_col, year):
    d = df[(df.year == year) & df.in_sample]
    return {g: pdata.weighted_median(x.networth, x.wgt) for g, x in d.groupby(group_col)}


def k(x):
    return f"${x / 1000:,.0f}k"


def main():
    # Own education, 1989 and 2025, straight from the Summary Extract zips.
    own = pd.concat([pdata.load_extract(y) for y in (1989, 2025)], ignore_index=True)
    own89 = medians_by_group(own, "own_educ_group", 1989)
    own25 = medians_by_group(own, "own_educ_group", 2025)

    # Parents' education, 2016 and 2025, from the full public files + extracts.
    par = pd.concat([pdata.load_year(y) for y in (2016, 2025)], ignore_index=True)
    par16 = medians_by_group(par, "group_ref", 2016)
    par25 = medians_by_group(par, "group_ref", 2025)

    # 2025 margins of error from the Fed's replicate weights (MEANIT method).
    ext, imp1 = se.load(2025)
    sample = lambda d: d.age.between(pdata.AGE_MIN, pdata.AGE_MAX) & (d.kids >= 1)
    err = se.estimate(ext, imp1, {
        "college": lambda d: sample(d) & (d.edcl == 4),
        "hs_or_less": lambda d: sample(d) & d.edcl.isin([1, 2]),
    }).set_index("statistic")

    # Cross-check against the tables the figures are drawn from.
    own_tbl = pd.read_csv(PROCESSED / "median_networth_by_own_educ.csv").set_index("year")
    par_tbl = pd.read_csv(PROCESSED / "median_networth_by_parent_educ.csv")
    par_tbl = par_tbl[par_tbl.definition == "ref"].set_index("year")
    for tbl, year, vals in [(own_tbl, 1989, own89), (own_tbl, 2025, own25),
                            (par_tbl, 2016, par16), (par_tbl, 2025, par25)]:
        for g in ("college", "hs_or_less"):
            if not np.isclose(tbl.loc[year, f"median_networth_{g}"], vals[g]):
                raise SystemExit(f"Processed table disagrees with raw data ({year}, {g}); "
                                 "rerun process_data.py")
    assert np.isclose(err.loc["median_college", "estimate"], own25["college"])

    c, h = err.loc["median_college"], err.loc["median_hs_or_less"]
    r = err.loc["ratio_college_to_hs"]

    text = f"""# ps158-wealth-lab

How family net worth differs by education in the United States, 1989–2025.

<!-- Generated by make_readme.py from the raw data. Do not edit by hand. -->

## Figures

All four cover **families with children whose reference person is aged
25–64**. Values are in **2025 dollars**.

| Figure | What it shows |
|---|---|
| `figures/median_networth_by_own_educ.png` | Median net worth by the reference person's **own** education, 1989–2025 |
| `figures/median_networth_by_parent_educ.png` | Median net worth by the reference person's **parents'** education, 2016–2025 |
| `figures/mean_networth_by_*.png` | The same two comparisons using means |

The two education measures are different questions, so they are kept on
separate figures.

## Key numbers

All computed from the raw files by `make_readme.py`.

**Own education** (bachelor's or higher vs high school or less):
- 1989: {k(own89['college'])} vs {k(own89['hs_or_less'])}, a ratio of {own89['college'] / own89['hs_or_less']:.1f}×.
- 2025: {k(own25['college'])} vs {k(own25['hs_or_less'])}, a ratio of {r.estimate:.1f}×.
- 2025 standard errors: ±{k(c.se_total)} and ±{k(h.se_total)}. 95% interval for the ratio: {r.ci95_low:.1f}–{r.ci95_high:.1f}×.

**Parents' education** (a parent with a bachelor's or higher vs neither past high school):
- 2016: {k(par16['college'])} vs {k(par16['hs_or_less'])}, a ratio of {par16['college'] / par16['hs_or_less']:.1f}×.
- 2025: {k(par25['college'])} vs {k(par25['hs_or_less'])}, a ratio of {par25['college'] / par25['hs_or_less']:.1f}×.

These are descriptive comparisons, not causal effects.

## Where the data come from

- **Federal Reserve Board, Survey of Consumer Finances** (https://www.federalreserve.gov/econres/scfindex.htm):
  - Summary Extract public data, 1989–2025: net worth (`NETWORTH`, already in 2025 dollars using CPI-U-RS), weights, education (`EDCL`), age, and number of children.
  - Full public data, 2016–2025: parents' education (`X6032`, `X6033`). This was first asked in 2016.
  - 2025 replicate weights, used for margins of error.
  - Published historical tables: every median and mean here reproduces the Fed's Table 4.
- **U.S. Census Bureau, SIPP 2024 wealth tables** (https://www.census.gov/data/tables/2024/demo/wealth/wealth-asset-ownership.html):
  - Used only as an independent cross-check (`compare_sources.py`).

Exact file URLs and SHA-256 hashes are listed in `data/raw/MANIFEST.csv`.

## Reproduce

```bash
python3 -m venv .venv && .venv/bin/pip install -r requirements.txt
.venv/bin/python get_data.py && .venv/bin/python process_data.py
.venv/bin/python standard_errors.py && .venv/bin/python plot.py
.venv/bin/python make_readme.py
```
"""
    (ROOT / "README.md").write_text(text)
    print("Wrote README.md")


if __name__ == "__main__":
    main()
